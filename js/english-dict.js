/* รูปผันที่เดาไม่ได้ด้วยกฎ */
const EN_IRREG={bought:'buy',sold:'sell',sent:'send',grew:'grow',grown:'grow',taught:'teach',took:'take',met:'meet',wrote:'write',written:'write',spoke:'speak',spoken:'speak',paid:'pay',fell:'fall',felt:'feel',held:'hold',went:'go',gave:'give',got:'get',told:'tell',better:'good',best:'good',children:'child',busier:'busy',busiest:'busy',studies:'study',studied:'study',lives:'live',boxes:'box',branches:'branch',parents:'parents',savings:'savings',sales:'sales',regards:'regards',earnings:'earnings',fees:'fee',funds:'fund'};
function enLemma(w){
  w=w.toLowerCase().replace(/[’']s$/,'');if(EN_DICT.has(w))return w;if(EN_IRREG[w]&&EN_DICT.has(EN_IRREG[w]))return EN_IRREG[w];
  const tries=[w.replace(/ies$/,'y'),w.replace(/es$/,''),w.replace(/s$/,''),w.replace(/ied$/,'y'),w.replace(/ed$/,''),w.replace(/d$/,''),w.replace(/(.)\1ed$/,'$1'),w.replace(/ing$/,''),w.replace(/ing$/,'e'),w.replace(/(.)\1ing$/,'$1'),w.replace(/est$/,''),w.replace(/er$/,''),w.replace(/r$/,''),w.replace(/st$/,'')];
  return tries.find(t=>t!==w&&EN_DICT.has(t))||'';
}
/* คำศัพท์ในโจทย์+ตัวเลือก ตามลำดับที่พบ ไม่ซ้ำ ไม่เกิน max คำ */
function enVocab(text,max){
  const out=[],seen=new Set();
  for(const raw of String(text||'').match(/[A-Za-z][A-Za-z’'-]*[A-Za-z]/g)||[]){const k=enLemma(raw);if(!k||seen.has(k))continue;seen.add(k);
    const [p,t]=EN_DICT.get(k);out.push(`${k}${raw.toLowerCase()!==k?` (${raw})`:''} ${p} = ${t}`);if(out.length>=(max||10))break}
  return out;
}
